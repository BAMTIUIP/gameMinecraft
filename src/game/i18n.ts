const DICTS: Record<Lang, Dict> = { en: EN, ru: RU, fr: FR };

let current: Lang = 'en';
const listeners = new Set<() => void>();

export function getLang() {
  return current;
}

export function setLang(l: Lang) {
  current = l;
  try {
    localStorage.setItem('orerush.lang', l);
  } catch {
    /* ignore */
  }
  listeners.forEach((fn) => fn());
}

export function initLang(): Lang {
  let l: Lang = 'en';
  try {
    const saved = localStorage.getItem('orerush.lang') as Lang | null;
    if (saved && DICTS[saved]) l = saved;
    else {
      const nav = navigator.language.slice(0, 2);
      if (nav === 'ru') l = 'ru';
      else if (nav === 'fr') l = 'fr';
    }
  } catch {
    /* ignore */
  }
  current = l;
  return l;
}

export function onLangChange(fn: () => void) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key: keyof Dict): string {
  return DICTS[current][key] ?? DICTS.en[key] ?? String(key);
}

