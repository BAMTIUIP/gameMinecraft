const DICTS: Record<Lang, Dict> = { en: EN, ru: RU, fr: FR, de: DE };

let current: Lang = 'en';
const listeners = new Set<() => void>();

export function getLang() {
  return current;
}

function syncDocument(l: Lang) {
  try {
    document.title = DICTS[l].docTitle;
    document.documentElement.lang = l;
  } catch {
    /* non-browser context */
  }
}

export function setLang(l: Lang) {
  current = l;
  storageSet('orerush.lang', l);
  syncDocument(l);
  listeners.forEach((fn) => fn());
}

export function initLang(): Lang {
  let l: Lang = 'en';
  try {
    const saved = storageGet('orerush.lang') as Lang | null;
    if (saved && DICTS[saved]) l = saved;
    else {
      const nav = navigator.language.slice(0, 2);
      if (nav === 'ru') l = 'ru';
      else if (nav === 'fr') l = 'fr';
      else if (nav === 'de') l = 'de';
    }
  } catch {
    /* ignore */
  }
  current = l;
  syncDocument(l);
  return l;
}

export function onLangChange(fn: () => void) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key: keyof Dict): string {
  return DICTS[current][key] ?? DICTS.en[key] ?? String(key);
}

